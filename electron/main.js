// Determine python executable
const getPythonPath = () => {
  const isWin = process.platform === 'win32';
  const venvFolder = isWin ? 'Scripts' : 'bin';
  const pythonExe = isWin ? 'python.exe' : 'python';
  
  // 1. Check for bundled python in resources (for packaged app)
  if (app.isPackaged) {
    return path.join(process.resourcesPath, 'venv', venvFolder, pythonExe);
  }

  // 2. Check for dev venv
  let venvPath;
  if (!isWin) {
    const pathFile = path.join(__dirname, '..', '.venv_linux_path');
    if (fs.existsSync(pathFile)) {
      const altPath = fs.readFileSync(pathFile, 'utf8').trim();
      if (altPath && fs.existsSync(altPath)) {
        venvPath = path.join(altPath, venvFolder, pythonExe);
      }
    }
  }
  
  if (!venvPath || !fs.existsSync(venvPath)) {
    const venvName = isWin ? 'venv' : 'venv_linux';
    venvPath = path.join(__dirname, '..', venvName, venvFolder, pythonExe);
  }
  
  if (!fs.existsSync(venvPath)) {
    // Fallback to 'venv' if venvName doesn't exist (e.g. if user only has one)
    venvPath = path.join(__dirname, '..', 'venv', venvFolder, pythonExe);
  }
  return venvPath;
};

const startBackend = () => {
  const logPath = app.isPackaged 
    ? path.join(app.getPath('userData'), 'backend.log')
    : path.join(__dirname, '..', 'backend.log');
    
  const out = fs.openSync(logPath, 'a');
  const err = fs.openSync(logPath, 'a');

  // Determine backend path and command
  let backendPath;
  let backendCmd;

  if (app.isPackaged) {
    // In production, we use the single-file executable generated by PyInstaller
    // On Windows/Wine it's .exe, on Linux it's just 'backend'
    const isWin = process.platform === 'win32';
    backendPath = path.join(process.resourcesPath, isWin ? 'backend.exe' : 'backend');
    backendCmd = backendPath;
  } else {
    // In development, we use the local venv and start_api.py
    backendCmd = getPythonPath();
    backendPath = path.join(__dirname, '..', 'start_api.py');
  }

  console.log(`Starting backend: ${backendCmd} ${app.isPackaged ? '' : backendPath}`);

  const backendArgs = app.isPackaged ? ['--port', API_PORT.toString()] : [backendPath, '--port', API_PORT.toString()];
  backendProcess = spawn(backendCmd, backendArgs, {
    cwd: app.isPackaged ? process.resourcesPath : path.join(__dirname, '..'),
    stdio: ['ignore', out, err], // Pipe to log file, retained from original
    windowsHide: true, // Retained from original
    detached: false,
    env: {
      ...process.env,
      // In packaged app, backend.exe handles its own environment
      // Only add the root to PYTHONPATH for dev mode.
      // Adding src/ or src/services/ causes our src/platform/ module to shadow
      // the Python standard library 'platform' module, breaking numpy/pandas.
      PYTHONPATH: app.isPackaged 
        ? process.resourcesPath // This might not be needed for backend.exe, but harmless
        : path.join(__dirname, '..')
    }
  });

  console.log(`Backend logging to: ${logPath}`);

  backendProcess.on('error', (err) => { // Changed from pythonProcess
    console.error('Failed to start backend process:', err);
  });

  backendProcess.on('exit', (code, signal) => {
    console.log(`Backend process exited with code ${code} and signal ${signal}`);
  });
};

function createSplashWindow() {
  splashWindow = new BrowserWindow({
    width: 400,
    height: 400,
    transparent: true,
    frame: false,
    alwaysOnTop: true,
    icon: iconPath,
    webPreferences: {
      nodeIntegration: true,
      contextIsolation: false
    }
  });

  splashWindow.loadFile(path.join(__dirname, 'splash.html'));
  return splashWindow;
}

function createWindow() {
  mainWindow = new BrowserWindow({
    width: 1280,
    height: 800,
    icon: iconPath,
    webPreferences: {
      nodeIntegration: false,
      contextIsolation: true,
      preload: app.isPackaged 
        ? path.join(__dirname, 'preload-loader.js') 
        : path.join(__dirname, 'preload.js'),
      backgroundThrottling: false,
      sandbox: false,
    },
    show: false, // Don't show until ready
    autoHideMenuBar: true,
  });

  // Load the app directly from the Python Backend
  mainWindow.loadURL(MAIN_URL);

  if (!app.isPackaged) {
    // mainWindow.webContents.openDevTools({ mode: 'detach' });
  }

  mainWindow.webContents.on('console-message', (event, level, message, line, sourceId) => {
    console.log(`[renderer:${level}] ${message} (${sourceId}:${line})`);
  });

  mainWindow.webContents.on('render-process-gone', (event, details) => {
    console.error('Renderer process gone:', details);
  });

  mainWindow.webContents.setWindowOpenHandler(({ url }) => {
    if (url.startsWith('http') && !url.includes(`127.0.0.1:${API_PORT}`) && !url.includes(`localhost:${API_PORT}`)) {
      shell.openExternal(url);
      return { action: 'deny' };
    }
    const child = new BrowserWindow({
      width: 1100,
      height: 720,
      parent: mainWindow,
      icon: iconPath,
      webPreferences: {
        nodeIntegration: false,
        contextIsolation: true,
        preload: app.isPackaged 
          ? path.join(__dirname, 'preload-loader.js') 
          : path.join(__dirname, 'preload.js'),
        backgroundThrottling: false,
      },
      autoHideMenuBar: true,
      show: true,
    });
    let targetUrl = url;
    try {
      const u = new URL(url);
      if (!u.searchParams.get("popout")) u.searchParams.set("popout", "true");
      targetUrl = u.toString();
    } catch (e) { }
    child.loadURL(targetUrl);
    return { action: 'deny' };
  });

  // Handle same-window navigation (rare but possible)
  mainWindow.webContents.on('will-navigate', (event, url) => {
    if (url.startsWith('http') && !url.includes(`127.0.0.1:${API_PORT}`) && !url.includes(`localhost:${API_PORT}`)) {
      event.preventDefault();
      shell.openExternal(url);
    }
  });

  mainWindow.once('ready-to-show', () => {
    if (splashWindow && !splashWindow.isDestroyed()) {
      splashWindow.close();
    }
    mainWindow.show();
  });

  mainWindow.on('closed', function () {
    mainWindow = null;
  });

  ipcMain.on('force-main-app', () => {
    console.log('[IPC] Forcing main app load (Admin bypass/Login request)');
    if (mainWindow) {
      mainWindow.loadURL(MAIN_URL);
    }
  });
}

// Check for single instance lock
const gotTheLock = app.requestSingleInstanceLock();

if (!gotTheLock) {
  app.quit();
} else {
  app.on('second-instance', (event, commandLine, workingDirectory) => {
    // Someone tried to run a second instance, we should focus our window.
    if (mainWindow) {
      if (mainWindow.isMinimized()) mainWindow.restore();
      mainWindow.focus();
    }
  });

  app.on('ready', async () => {
    // Si estamos en Linux, creamos los accesos directos de forma automatizada
    if (process.platform === 'linux') {
      try {
        const scriptPath = path.join(__dirname, '..', 'scripts', 'setup_shortcuts.sh');
        if (fs.existsSync(scriptPath)) {
          console.log(`[Linux Shortcuts] Iniciando creación de accesos directos usando: ${scriptPath}`);
          const mainExec = app.isPackaged ? process.execPath : path.join(__dirname, '..', 'node_modules', '.bin', 'electron');
          const trainerExec = app.isPackaged 
            ? path.join(process.resourcesPath, 'Trainer') 
            : path.join(__dirname, '..', 'venv_linux', 'bin', 'python') + ' ' + path.join(__dirname, '..', 'run.py');
          const browserExec = app.isPackaged 
            ? path.join(process.resourcesPath, 'BrowserMode') 
            : path.join(__dirname, '..', 'venv_linux', 'bin', 'python') + ' ' + path.join(__dirname, '..', 'browser_launcher.py');
          const iconPng = path.join(__dirname, '..', 'images', 'QuantumLLama.png');
          
          exec(`bash "${scriptPath}" "${mainExec}" "${trainerExec}" "${browserExec}" "${iconPng}"`, (err, stdout, stderr) => {
            if (err) {
              console.error('[Linux Shortcuts] Error ejecutando script de accesos directos:', err);
            } else {
              console.log('[Linux Shortcuts] Accesos directos procesados:', stdout);
            }
          });
        }
      } catch (err) {
        console.error('[Linux Shortcuts] Error al procesar accesos directos:', err);
      }
    }

    API_PORT = await findRunningBackend();
    if (!API_PORT) {
        API_PORT = await getFreePort(8050);
    }
    MAIN_URL = `http://${API_HOST}:${API_PORT}`;

    createSplashWindow();
    startBackend();

    // Monitor backend process
    backendProcess.on('exit', (code) => {
        console.error(`[BACKEND_PROCESS] Exited with code: ${code}`);
        if (mainWindow && !mainWindow.isDestroyed()) {
            mainWindow.webContents.executeJavaScript(`console.error("[BACKEND_WATCH] Backend exited early with code ${code}")`);
        }
    });

    try {
        console.log(`Waiting for backend at http://127.0.0.1:${API_PORT}/api/health...`);
        // Use waitOn to make sure backend is up
        await waitOn({
            resources: [`http://127.0.0.1:${API_PORT}/api/health`],
            timeout: 30000, // Wait 30s
        });

        console.log(`Backend started and healthy at 127.0.0.1:${API_PORT}`);
        
        // Verificación de Licencia Hardware
        const checkLicense = () => {
          return new Promise((resolve) => {
            const req = http.get(`http://127.0.0.1:${API_PORT}/api/license/check`, (res) => {
              let data = '';
              res.on('data', (chunk) => data += chunk);
              res.on('end', () => {
                try {
                  resolve(JSON.parse(data));
                } catch (e) {
                  resolve({ allowed: true, reason: 'parse_error_fallback' });
                }
              });
            });
            req.on('error', (err) => {
              console.error('License check request failed:', err);
              resolve({ allowed: true, reason: 'offline_fallback' });
            });
            req.end();
          });
        };

        const licenseStatus = await checkLicense();
        if (!licenseStatus.allowed) {
          console.warn('License check denied:', licenseStatus.reason);
          createWindow();
          mainWindow.loadFile(path.join(__dirname, 'trial-expired.html'));
        } else {
          createWindow();
        }
    } catch (err) {
        console.error('Backend failed to start or timeout:', err);
        // Fallback: still show window so user can see something is wrong
        createWindow();
    }
  });
}

app.on('window-all-closed', function () {
  if (process.platform !== 'darwin') app.quit();
});

app.on('will-quit', () => {
  if (backendProcess) {
    console.log('Killing backend process...');
    treeKill(backendProcess.pid, 'SIGKILL', (err) => {
      if (err) console.error('Error killing backend process:', err);
    });
  }
});
